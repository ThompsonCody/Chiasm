export interface Work {
  id: string;
  title: string;
  description: string;
  aliases?: readonly string[];
}
export interface Collection {
  id: string;
  title: string;
  sourceUrl?: string;
  note: string;
  /** Source labels are retained separately from normalized work titles. */
  sourceLabels?: Readonly<Record<string, string>>;
  groups: readonly { title: string; workIds: readonly string[] }[];
}

const work = (
  id: string,
  title: string,
  aliases: string[] = [],
  description = "A work in the shared library. Reading editions are listed separately.",
): Work => ({ id, title, aliases, description });

